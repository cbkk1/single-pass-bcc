#!/usr/bin/env python3
"""Splice the freshly generated Table 1 into the self-contained .tex files.

    python3 experiments/sync-selfcontained.py <file.tex> [<file.tex> ...]

paper/results.tex is generated by gen-table.py and \\input by
algorithms-standalone.tex, so that one is always current. But two files inline
the table instead and so go stale silently:
  * paper/main-overleaf.tex   -- the single file for pasting into Overleaf
  * the main.tex in the cbkk1/BCC clone  -- what GitHub serves
Both diverged unnoticed once already. This copies two regions -- the legend and
the data rows -- and leaves everything else (the citation form, table vs
table*, the prose) untouched, because those legitimately differ per file.
"""
import re, sys

src = open("paper/results.tex").read()


def region(s, start, end, what):
    i = s.index(start) + len(start)
    j = s.index(end, i)
    return i, j, s[i:j]


# legend: between the fixed lead-in and the brace that closes \caption
L_A, L_B = "$|E|$ is the undirected edge count.\n", "}\n\\label{tab:speedup}"
# data rows: the body of the tabular
R_A, R_B = "\\midrule\n", "\\bottomrule"

_, _, legend = region(src, L_A, L_B, "legend")
_, _, rows = region(src, R_A, R_B, "rows")
nrow = len([x for x in rows.splitlines() if x.startswith("~~")])
assert nrow > 20, f"only {nrow} data rows parsed from results.tex -- refusing"

for path in sys.argv[1:]:
    s = open(path).read()
    out = s
    for a, b, new, what in ((L_A, L_B, legend, "legend"), (R_A, R_B, rows, "rows")):
        try:
            i, j, old = region(out, a, b, what)
        except ValueError:
            sys.exit(f"{path}: could not locate the {what} region")
        if old == new:
            print(f"  {path}: {what} already current")
        else:
            out = out[:i] + new + out[j:]
            print(f"  {path}: {what} updated")
    if out != s:
        open(path, "w").write(out)
print(f"synced {nrow} data rows")
